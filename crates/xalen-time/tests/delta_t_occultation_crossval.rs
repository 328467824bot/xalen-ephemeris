/// Convert a Julian year to a Julian Date (UT) — inverse of the model's internal
/// `jd_to_year` (2000.0 + (jd − J2000)/365.25).
fn year_to_jd(year: f64) -> f64 {
    2_451_545.0 + (year - 2000.0) * 365.25
}

/// The SMH2016 spline must be the UNBIASED fit to the raw occultation ΔT record:
/// weighted-mean residual ≈ 0, weighted RMS small and consistent with the
/// observational scatter (not a sign of model error).
#[test]
fn smh_spline_is_unbiased_fit_to_occultation_record() {
    let model = DeltaTModel::StephensonMorrisonHohenkerk2016;
    let (mut sw, mut swr, mut swr2) = (0.0_f64, 0.0_f64, 0.0_f64);
    for &(year, observed_dt, wt) in OCCULTATION_DT {
        let res = delta_t(year_to_jd(year), &model) - observed_dt;
        sw += wt;
        swr += wt * res;
        swr2 += wt * res * res;
    }
    let w_mean = swr / sw;
    let w_rms = (swr2 / sw).sqrt();
    assert!(
        w_mean.abs() < 0.5,
        "ΔT spline must be an UNBIASED fit to the occultation record; \
         weighted-mean residual = {w_mean:+.4} s (expected near 0)"
    );
    assert!(
        w_rms < 5.0,
        "weighted RMS residual {w_rms:.4} s too large — spline should track \
         observations within their scatter"
    );
}

/// In the precise modern era (year > 1960) the spline must track the dense,
/// high-weight observations tightly — under 2 s weighted RMS.
#[test]
fn smh_spline_tracks_modern_occultations_tightly() {
    let model = DeltaTModel::StephensonMorrisonHohenkerk2016;
    let (mut sw, mut swr2) = (0.0_f64, 0.0_f64);
    for &(year, observed_dt, wt) in OCCULTATION_DT {
        if year < 1960.0 {
            continue;
        }
        let res = delta_t(year_to_jd(year), &model) - observed_dt;
        sw += wt;
        swr2 += wt * res * res;
    }
    let w_rms = (swr2 / sw).sqrt();
    assert!(
        w_rms < 2.0,
        "post-1960 weighted RMS {w_rms:.4} s should be < 2 s (precise modern era)"
    );
}
